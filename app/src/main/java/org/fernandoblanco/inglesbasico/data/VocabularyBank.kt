    /**
     * Genera exactamente [count] opciones en inglés, sin duplicados (ignorando mayúsculas).
     */
    fun randomOptions(correct: VocabItem, pool: List<VocabItem>, count: Int = 4): List<String> {
        val resultado = mutableListOf(correct.en)
        val vistos = mutableSetOf(correct.enKey)
        val mezcla = pool
            .filter { !it.enKey.equals(correct.enKey, ignoreCase = true) }
            .map { it.en }
            .shuffled()
        for (txt in mezcla) {
            if (resultado.size >= count) break
            val k = txt.lowercase()
            if (k !in vistos) {
                vistos.add(k)
                resultado.add(txt)
            }
        }
        if (resultado.size < count) {
            for (item in pool.shuffled()) {
                if (resultado.size >= count) break
                val t = item.en
                val k = t.lowercase()
                if (k !in vistos) {
                    vistos.add(k)
                    resultado.add(t)
                }
            }
        }
        return resultado.shuffled()
    }

    /** Enmascara letras internas para el juego de completar (palabra en mayúsculas). */
    fun enmascarar(en: String): Pair<String, String> {
        val letters = en.filter { it.isLetter() }
        if (letters.length < 2) return en.uppercase() to en.uppercase()
        val upper = en.uppercase()
        val idx = en.indices.filter { en[it].isLetter() }
        val hideCount = (idx.size / 2).coerceIn(1, idx.size - 1)
        val hidden = idx.shuffled().take(hideCount).toSet()
        val sb = StringBuilder(upper)
        hidden.forEach { i ->
            if (sb[i].isLetter()) sb[i] = '_'
        }
        return sb.toString() to upper
    }
